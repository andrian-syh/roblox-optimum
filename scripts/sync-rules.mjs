#!/usr/bin/env node
/**
 * Writes the per-agent copies of AGENTS.md and proves they have not drifted. AGENTS.md is the only
 * text anyone edits, so a copy that falls behind teaches one agent a rule the others dropped.
 */

import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { PROFILE_ID } from "./lib/host-contract.mjs";
import { ranAsScript } from "./lib/package.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = "AGENTS.md";

/**
 * The host profiles, and the index that imports them. The index is settled before anything that
 * loads it is imported, so adding or removing a profile can never break this script itself.
 */
const HOSTS_DIR = "scripts/lib/hosts";
const HOSTS_INDEX = `${HOSTS_DIR}/index.mjs`;

/** The static index of every profile file, sorted byte-wise so every machine writes the same text. */
function hostsIndex() {
  const files = readdirSync(join(ROOT, HOSTS_DIR))
    .filter((name) => name.endsWith(".mjs") && name !== "index.mjs")
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

  for (const name of files) {
    if (!PROFILE_ID.test(name.slice(0, -4))) throw new Error(`${HOSTS_DIR}/${name}: a profile file name must be a kebab-case id`);
  }

  const binding = (name) => name.slice(0, -4).replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
  return [
    "/**",
    " * Generated by scripts/sync-rules.mjs from the profile files in this folder. Add a host as a",
    " * new file here and run it; never edit this file.",
    " */",
    "",
    ...files.map((name) => `import ${binding(name)} from "./${name}";`),
    "",
    "export const PROFILE_FILES = [",
    ...files.map((name) => `  ["${name}", ${binding(name)}],`),
    "];",
    "",
  ].join("\n");
}

/** The text one target should hold: its front matter, a line saying not to edit it, then the shared body. */
function render(body, frontMatter, generated) {
  return `${frontMatter}${generated}\n\n${body}`;
}

/**
 * The Codex hook file, made from the Claude one. Codex names its plugin root differently, and a
 * hook that expands to nothing fails silently.
 */
const HOOKS_SOURCE = "hooks/hooks.json";
const HOOKS_TARGET = "hooks/codex-hooks.json";

/**
 * Rewrites the Claude hooks for Codex: arguments fold into the command string, the host id and
 * the patch tool are Codex's, and MCP tool matchers are dropped, since Codex is unproven on them.
 */
function codexHooks(text) {
  const config = JSON.parse(text);

  for (const [event, all] of Object.entries(config.hooks)) {
    const entries = all.filter((entry) => !(entry.matcher ?? "").startsWith("mcp__"));
    config.hooks[event] = entries;
    for (const entry of entries) {
      if (typeof entry.matcher === "string") {
        entry.matcher = entry.matcher.split("|").filter((name) => !name.startsWith("mcp__")).join("|");
      }
      if (entry.matcher === "Write|Edit|MultiEdit") entry.matcher = "apply_patch|Edit|Write";

      for (const hook of entry.hooks) {
        if (!Array.isArray(hook.args)) continue;

        const args = hook.args
          .map((arg) => arg.replaceAll("CLAUDE_PLUGIN_ROOT", "PLUGIN_ROOT"))
          .map((arg) => (arg === "claude-code" ? "codex" : arg))
          .map((arg) => (/[\s$]/.test(arg) ? `"${arg}"` : arg));
        hook.command = [hook.command, ...args].join(" ");
        delete hook.args;
      }
    }
  }

  return `${JSON.stringify(config, null, 2)}\n`;
}

/**
 * The MCP entry, and the filename Antigravity reads it under. The two files are identical, and
 * a host is reached by the name it looks for rather than by a second copy kept in step by hand.
 */
const MCP_SOURCE = "mcp.json";
const MCP_TARGET = "mcp_config.json";

/**
 * The agents, and where Copilot reads them. It searches a directory of its own and requires the
 * .agent.md suffix, so the file this repository writes for Claude Code is invisible to it.
 */
const AGENTS_SOURCE = "agents";
const AGENTS_TARGET = ".github/agents";

async function derive() {
  const { RULE_TARGETS, GENERATED, forCopilot } = await import("./roblox-optimum.mjs");
  const body = readFileSync(join(ROOT, SOURCE), "utf8").replace(/\r\n/g, "\n");
  const hooks = readFileSync(join(ROOT, HOOKS_SOURCE), "utf8").replace(/\r\n/g, "\n");

  const copilotAgents = readdirSync(join(ROOT, AGENTS_SOURCE))
    .filter((name) => name.endsWith(".md"))
    .map((name) => [
      `${AGENTS_TARGET}/${name.replace(/\.md$/, ".agent.md")}`,
      forCopilot(readFileSync(join(ROOT, AGENTS_SOURCE, name), "utf8").replace(/\r\n/g, "\n")),
    ]);

  return [
    ...RULE_TARGETS.map((target) => [target.path, render(body, target.frontMatter, GENERATED)]),
    [HOOKS_TARGET, codexHooks(hooks)],
    [MCP_TARGET, readFileSync(join(ROOT, MCP_SOURCE), "utf8").replace(/\r\n/g, "\n")],
    ...copilotAgents,
  ];
}

function readText(path) {
  try {
    return readFileSync(join(ROOT, path), "utf8").replace(/\r\n/g, "\n");
  } catch {
    return "";
  }
}

async function sync(check) {
  const index = hostsIndex();
  if (check && readText(HOSTS_INDEX) !== index) {
    console.error(`sync-rules: ${HOSTS_INDEX} is out of date\n\nRun: node scripts/sync-rules.mjs\n`);
    return 1;
  }
  if (!check) writeFileSync(join(ROOT, HOSTS_INDEX), index);

  const files = [[HOSTS_INDEX, index], ...(await derive())];
  const drifted = [];

  for (const [path, wanted] of files) {
    const full = join(ROOT, path);

    if (check) {
      if (readText(path) !== wanted) drifted.push(path);
      continue;
    }

    mkdirSync(dirname(full), { recursive: true });
    writeFileSync(full, wanted);
  }

  if (!check) {
    console.log(`sync-rules: wrote ${files.length} derived files`);
    return 0;
  }

  if (drifted.length > 0) {
    console.error(
      `sync-rules: ${drifted.length} derived file is out of date:\n` +
        drifted.map((p) => `  - ${p}`).join("\n") +
        `\n\nRun: node scripts/sync-rules.mjs\n`,
    );
    return 1;
  }

  console.log(`sync-rules: ${files.length} derived files are current`);
  return 0;
}

if (ranAsScript(import.meta.url)) {
  const mode = process.argv[2];

  if (mode !== undefined && mode !== "--check") {
    process.stderr.write(
      `sync-rules: unknown option ${mode}\n\nUsage: sync-rules.mjs [--check]\n`,
    );
    process.exit(2);
  }

  process.exit(await sync(mode === "--check"));
}
